const spanishText = Object.fromEntries(
  Object.entries(valencianText).map(([spanish, valencian]) => [valencian, spanish])
);

const languageToggle = document.querySelector("#language-toggle");
const textWalker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
const textNodes = [];

while (textWalker.nextNode()) {
  if (textWalker.currentNode.parentElement.closest("script, style")) continue;
  textNodes.push(textWalker.currentNode);
}

const translatableAttributes = ["alt", "aria-label", "content"];
const translatableElements = [...document.querySelectorAll(translatableAttributes.map(attribute => `[${attribute}]`).join(","))];

function setLanguage(language) {
  const isValencian = language === "val";
  const dictionary = isValencian ? valencianText : spanishText;

  for (const node of textNodes) {
    const originalText = node.nodeValue;
    const trimmedText = originalText.trim();
    if (!Object.hasOwn(dictionary, trimmedText)) continue;
    node.nodeValue = originalText.replace(trimmedText, dictionary[trimmedText]);
  }

  for (const element of translatableElements) {
    for (const attribute of translatableAttributes) {
      const value = element.getAttribute(attribute);
      if (value && Object.hasOwn(dictionary, value)) element.setAttribute(attribute, dictionary[value]);
    }
  }

  document.documentElement.lang = isValencian ? "ca-valencia" : "es";
  document.title = isValencian
    ? valencianText["Marina Alta al Día — La actualidad, de frente"]
    : "Marina Alta al Día — La actualidad, de frente";
  languageToggle.textContent = isValencian ? "Castellano" : "Valencià";
  languageToggle.setAttribute("aria-label", isValencian ? "Canvia a castellà" : "Cambiar a valenciano");
}

languageToggle.addEventListener("click", () => {
  setLanguage(document.documentElement.lang === "es" ? "val" : "es");
});

