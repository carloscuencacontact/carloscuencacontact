const languageToggle = document.querySelector("#language-toggle");
const textWalker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
const textNodes = [];

while (textWalker.nextNode()) {
  if (textWalker.currentNode.parentElement.closest("script, style")) continue;
  textNodes.push(textWalker.currentNode);
}

const translatableAttributes = ["alt", "aria-label", "content"];
const translatableElements = [...document.querySelectorAll(translatableAttributes.map(attribute => `[${attribute}]`).join(","))];

function setLanguage(language) {
  const isValencian = language === "val";
  const dictionary = isValencian ? valencianText : spanishText;

  for (const node of textNodes) {
    const originalText = node.nodeValue;
    const trimmedText = originalText.trim();
    if (!Object.hasOwn(dictionary, trimmedText)) continue;
    node.nodeValue = originalText.replace(trimmedText, dictionary[trimmedText]);
  }

  for (const element of translatableElements) {
    for (const attribute of translatableAttributes) {
      const value = element.getAttribute(attribute);
      if (value && Object.hasOwn(dictionary, value)) element.setAttribute(attribute, dictionary[value]);
    }
  }

  document.documentElement.lang = isValencian ? "ca-valencia" : "es";
  document.title = isValencian
    ? valencianText["El Vèrtex — Actualidad, de frente"]
    : "El Vèrtex — Actualidad, de frente";
  languageToggle.textContent = isValencian ? "Castellano" : "Valencià";
  languageToggle.setAttribute("aria-label", isValencian ? "Canvia a castellà" : "Cambiar a valenciano");
}

languageToggle.addEventListener("click", () => {
  setLanguage(document.documentElement.lang === "es" ? "val" : "es");
});

const carouselTrack = document.querySelector(".story-grid");
const carouselViewport = document.querySelector(".carousel-viewport");
const carouselCards = [...document.querySelectorAll(".story-card")];
const carouselDots = [...document.querySelectorAll(".carousel-dot-button")];
let activeSlide = 0;

function showSlide(index) {
  activeSlide = (index + carouselCards.length) % carouselCards.length;
  carouselTrack.style.transform = `translateX(-${activeSlide * 100}%)`;
  carouselDots.forEach((dot, dotIndex) => {
    if (dotIndex === activeSlide) dot.setAttribute("aria-current", "true");
    else dot.removeAttribute("aria-current");
  });
}

document.querySelector(".carousel-previous").addEventListener("click", () => showSlide(activeSlide - 1));
document.querySelector(".carousel-next").addEventListener("click", () => showSlide(activeSlide + 1));
carouselDots.forEach((dot, index) => {
  dot.addEventListener("click", () => showSlide(index));
});

let swipeStartX = null;
carouselViewport.addEventListener("pointerdown", event => {
  if (event.pointerType === "touch") swipeStartX = event.clientX;
});
carouselViewport.addEventListener("pointerup", event => {
  if (swipeStartX === null) return;
  const swipeDistance = swipeStartX - event.clientX;
  if (Math.abs(swipeDistance) > 40) showSlide(activeSlide + (swipeDistance > 0 ? 1 : -1));
  swipeStartX = null;
});
carouselViewport.addEventListener("pointercancel", () => {
  swipeStartX = null;
});
